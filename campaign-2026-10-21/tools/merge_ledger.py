#!/usr/bin/env python3
"""Merge ledger.d/*.json fragments into ledger.json and regenerate STATUS.md.

Fragments win over existing ledger.json entries for the same repo, except that
publication fields (status PUBLISHED, upstream_pr) recorded in ledger.json are
kept. Also flags any non-held patch that lacks the visible Deploy to Wasmer
badge. Run from anywhere: python3 -I tools/merge_ledger.py
"""
import glob
import json
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
BADGE = "img.shields.io/badge/Deploy%20to-Wasmer-171717?logo=wasmer&logoColor=white"
ORDER = ["PUBLISHED", "READY", "HOOK_BLOCKED", "HELD_RUNTIME", "HELD_BUILD", "HELD_POLICY", "EXCLUDED"]


def main():
    path = os.path.join(ROOT, "ledger.json")
    ledger = json.load(open(path))
    targets = {t["repo"]: t for t in ledger["targets"]}
    for frag in sorted(glob.glob(os.path.join(ROOT, "ledger.d", "*.json"))):
        entry = json.load(open(frag))
        old = targets.get(entry["repo"], {})
        if old.get("status") == "PUBLISHED":
            entry["status"], entry["upstream_pr"] = "PUBLISHED", old["upstream_pr"]
        targets[entry["repo"]] = {**old, **entry}

    problems = []
    for repo, t in targets.items():
        patch = (t.get("patch") or "").split(" ")[0]
        if t.get("status") in ("PUBLISHED", "READY", "HELD_BUILD") and patch:
            text = open(os.path.join(ROOT, patch)).read()
            if not any(BADGE in line for line in text.splitlines() if line.startswith("+")):
                problems.append(f"{repo}: patch lacks visible badge")
        if t.get("status") == "READY" and not t.get("pr_body"):
            problems.append(f"{repo}: READY without pr_body")

    ledger["targets"] = sorted(targets.values(), key=lambda t: (ORDER.index(t.get("status", "EXCLUDED")), t["repo"].lower()))
    ledger.pop("queued_static_candidates", None)
    with open(path, "w") as f:
        json.dump(ledger, f, indent=2)
        f.write("\n")

    rows = ["| # | Repo | Status | Stars | Normal build | Anybuild replay | Detection | Upstream PR |", "|---|---|---|---|---|---|---|---|"]
    for i, t in enumerate(ledger["targets"], 1):
        build = t.get("build_claude", "")
        build = str(build.get("result", build) if isinstance(build, dict) else build)
        build = build.split(":")[0].split(" ")[0] if build else ""
        if t.get("build_external"):
            build += " / ext PASS"
        det = str(t.get("detection_verified", "")).split("(")[0].strip()[:24]
        replay = str(t.get("anybuild_replay", "")).split(":")[0]
        rows.append(f"| {i} | {t['repo']} | {t.get('status')} | {t.get('stars', '')} | {build} | {replay} | {det} | {t.get('upstream_pr', '').split(' ')[0]} |")
    counts = {s: sum(t.get("status") == s for t in ledger["targets"]) for s in ORDER}
    with open(os.path.join(ROOT, "STATUS.md"), "w") as f:
        f.write("# Campaign status (generated by tools/merge_ledger.py; ledger.json is authoritative)\n\n")
        f.write(" · ".join(f"{s}: {n}" for s, n in counts.items()) + "\n\n")
        f.write("\n".join(rows) + "\n")
        if problems:
            f.write("\n## Problems\n\n" + "\n".join(f"- {p}" for p in problems) + "\n")
    print(json.dumps(counts))
    print("\n".join(problems) or "no problems")


if __name__ == "__main__":
    main()
